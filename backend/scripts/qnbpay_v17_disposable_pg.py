"""V17 concurrent unique-constraint check, *exclusively* for an isolated PostgreSQL test database.

Never execute against production. Requires a database whose exact name is
lidyachat_v17_test and an explicit operator consent environment variable.
Creates only disposable test tables inside an ephemeral schema and drops that
schema on exit. Does not import the app, access orders, or write to wallet.
"""
from __future__ import annotations

import os
import secrets
from concurrent.futures import ThreadPoolExecutor
from threading import Barrier

from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import IntegrityError

REQUIRED_DATABASE = 'lidyachat_v17_test'
CONSENT = 'I_CREATED_A_SEPARATE_V17_TEST_DATABASE'


def validate_target(url: str, consent: str) -> str:
    if consent != CONSENT:
        raise ValueError('Explicit disposable database confirmation missing')
    if not url:
        raise ValueError('V17_TEST_DATABASE_URL is required')
    parsed = make_url(url)
    if parsed.get_backend_name() != 'postgresql' or parsed.database != REQUIRED_DATABASE:
        raise ValueError('Refusing any target except isolated PostgreSQL database lidyachat_v17_test')
    if not parsed.host or parsed.host in ('localhost', '127.0.0.1') and os.environ.get('V17_ALLOW_LOCALHOST') != 'YES':
        raise ValueError('Host missing or local target not explicitly allowed')
    return url


def main() -> int:
    url = validate_target(os.getenv('V17_TEST_DATABASE_URL', ''), os.getenv('V17_DISPOSABLE_DB_CONFIRM', ''))
    engine = create_engine(url, pool_pre_ping=True, connect_args={'connect_timeout': 5, 'options': '-c statement_timeout=15000 -c lock_timeout=10000'})
    schema = 'v17_disposable_' + secrets.token_hex(6)
    table = f'{schema}.payment_claims'
    try:
        with engine.begin() as conn:
            conn.execute(text(f'CREATE SCHEMA {schema}'))
            conn.execute(text(f'''CREATE TABLE {table} (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                provider varchar(24) NOT NULL,
                transaction_id varchar(128) NOT NULL,
                order_ref varchar(36) NOT NULL,
                wc_order_id bigint NOT NULL,
                state varchar(24) NOT NULL DEFAULT 'unverified',
                CONSTRAINT uq_v17_provider_tx UNIQUE (provider, transaction_id),
                CONSTRAINT uq_v17_order_ref UNIQUE (order_ref),
                CONSTRAINT uq_v17_wc_order_id UNIQUE (wc_order_id),
                CONSTRAINT ck_v17_state CHECK (state = 'unverified')
            )'''))
        # These records are synthetic and exist only in the ephemeral test schema.
        def insert(row: tuple[str, str, int]) -> bool:
            tx_id, order_ref, wc_id = row
            try:
                with engine.begin() as c:
                    c.execute(text(f'''INSERT INTO {table} (provider, transaction_id, order_ref, wc_order_id)
                          VALUES ('QNBpay', :tx_id, :order_ref, :wc_id)'''),
                          {'tx_id': tx_id, 'order_ref': order_ref, 'wc_id': wc_id})
                return True
            except IntegrityError:
                return False

        tx = 'v17tx_' + secrets.token_hex(12)
        a = ('11111111-1111-4111-8111-111111111111')
        b = ('22222222-2222-4222-8222-222222222222')
        assert insert((tx, a, 10001)), 'Initial insert failed'
        assert not insert((tx, b, 10002)), 'Duplicate transaction accepted'
        assert not insert((tx + 'other', a, 10003)), 'Duplicate order reference accepted'
        assert not insert((tx + 'third', b, 10001)), 'Duplicate Woo order ID accepted'
        barrier = Barrier(2)
        tx2 = 'v17tx_' + secrets.token_hex(12)

        def racing_insert(index: int) -> bool:
            barrier.wait(timeout=8)
            return insert((tx2, f'{index+3:08d}-3333-4333-8333-333333333333', 20000 + index))

        with ThreadPoolExecutor(max_workers=2) as executor:
            futures = [executor.submit(racing_insert, i) for i in range(2)]
            results = [f.result(timeout=20) for f in futures]
        if results.count(True) != 1 or results.count(False) != 1:
            raise RuntimeError(f'Concurrency unique guard failed: {results}')
        with engine.connect() as conn:
            count = conn.execute(text(f'SELECT count(*) FROM {table}')).scalar_one()
        if count != 2:
            raise RuntimeError('Unexpected test-only record count')
        print('V17 POSTGRESQL PASS: provider transaction / order reference / WC order unique')
        print('V17 CONCURRENCY PASS: exactly one of two simultaneous duplicate transactions committed')
        print('No app orders, live payment, or coin balance modified')
        return 0
    finally:
        # Never leave test records behind; only operates inside the guarded disposable database.
        try:
            with engine.begin() as conn:
                conn.execute(text(f'DROP SCHEMA IF EXISTS {schema} CASCADE'))
        finally:
            engine.dispose()


if __name__ == '__main__':
    raise SystemExit(main())
